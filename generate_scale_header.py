"""
Generates scaler_params.h from the scalers/metadata.json file produced by
imu_normalizer.py. Run this once after fitting your scalers, then include
the header in your ESP32-IDF project.

USAGE:
    python generate_scaler_header.py
    # outputs: scaler_params.h  (copy this into your ESP-IDF main/ folder)
"""

import json
import os

SCALER_DIR = "./scalers"
OUTPUT_HEADER = "scaler_params.h"


def format_float_array(values: list[float], indent: int = 4) -> str:
    """Format a Python list of floats as a C brace-initializer."""
    pad = " " * indent
    entries = [f"{pad}{v:.10f}f" for v in values]
    return "{\n" + ",\n".join(entries) + "\n}"


def generate_header(meta: dict) -> str:
    feature_mean  = meta["feature_mean"]
    feature_scale = meta["feature_scale"]
    euler_mean    = meta["euler_mean"]
    euler_scale   = meta["euler_scale"]
    feature_cols  = meta.get("feature_cols", [f"f{i}" for i in range(len(feature_mean))])

    n_features = len(feature_mean)
    n_euler    = len(euler_mean)

    col_comments = "\n".join(
        f" *   [{i}] {col}" for i, col in enumerate(feature_cols)
    )

    lines = [
        "/**",
        " * scaler_params.h",
        " * Auto-generated by generate_scaler_header.py",
        " * DO NOT EDIT MANUALLY.",
        " *",
        " * Apply BEFORE feeding sensor data into the model:",
        " *   normalized = (raw - FEATURE_MEAN[i]) / FEATURE_SCALE[i]",
        " *",
        " * Apply AFTER reading Euler output from the model:",
        " *   degrees = normalized * EULER_SCALE[i] + EULER_MEAN[i]",
        " *",
        " * Feature column order:",
        col_comments,
        " */",
        "",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"// Number of input sensor channels (must match model input features)",
        f"constexpr int NUM_FEATURES = {n_features};",
        "",
        f"// Number of Euler angle outputs",
        f"constexpr int NUM_EULER = {n_euler};",
        "",
        "// ---- Feature normalization (StandardScaler) ----",
        "// normalized_feature[i] = (raw[i] - FEATURE_MEAN[i]) / FEATURE_SCALE[i]",
        f"constexpr float FEATURE_MEAN[{n_features}] = {format_float_array(feature_mean)};",
        "",
        f"constexpr float FEATURE_SCALE[{n_features}] = {format_float_array(feature_scale)};",
        "",
        "// ---- Euler angle denormalization (inverse StandardScaler) ----",
        "// euler_degrees[i] = model_output[i] * EULER_SCALE[i] + EULER_MEAN[i]",
        f"constexpr float EULER_MEAN[{n_euler}] = {format_float_array(euler_mean)};",
        "",
        f"constexpr float EULER_SCALE[{n_euler}] = {format_float_array(euler_scale)};",
        "",
        "// ---- Inline helper: normalize one feature vector in-place ----",
        "// Call this on raw sensor readings before passing to Model::predict()",
        "inline void normalize_features(float* features, int n) {",
        "    for (int i = 0; i < n && i < NUM_FEATURES; i++) {",
        "        features[i] = (features[i] - FEATURE_MEAN[i]) / FEATURE_SCALE[i];",
        "    }",
        "}",
        "",
        "// ---- Inline helper: denormalize Euler angles in-place ----",
        "// Call this on the first NUM_EULER elements of Model::predict() output",
        "inline void denormalize_euler(float* euler, int n) {",
        "    for (int i = 0; i < n && i < NUM_EULER; i++) {",
        "        euler[i] = euler[i] * EULER_SCALE[i] + EULER_MEAN[i];",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main():
    meta_path = os.path.join(SCALER_DIR, "metadata.json")
    if not os.path.exists(meta_path):
        print(f"ERROR: {meta_path} not found. Run `python imu_normalizer.py` first.")
        return

    with open(meta_path) as f:
        meta = json.load(f)

    header_content = generate_header(meta)

    with open(OUTPUT_HEADER, "w") as f:
        f.write(header_content)

    print(f"✅ Generated: {OUTPUT_HEADER}")
    print(f"   Features : {len(meta['feature_mean'])} channels")
    print(f"   Euler    : {len(meta['euler_mean'])} outputs")
    print(f"\nCopy {OUTPUT_HEADER} into your ESP-IDF project's main/ directory.")


if __name__ == "__main__":
    main()